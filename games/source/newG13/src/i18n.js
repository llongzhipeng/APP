export function createI18n() {
  const stored = localStorage.getItem('zoo_lang');
  return {
    lang: stored === 'en' ? 'en' : 'zh',
    t(key) {
      return translations[this.lang][key] || key;
    },
    setLang(l) {
      this.lang = l;
      localStorage.setItem('zoo_lang', l);
    },
  };
}
