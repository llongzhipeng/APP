export function t(lang, key, params) {
  let s = (DICT[lang] && DICT[lang][key]) || DICT.zh[key] || key;
  if (params) {
    Object.keys(params).forEach((k) => {
      s = s.replace(new RegExp(`{${k}}`, 'g'), params[k]);
    });
  }
  return s;
}
