export const i18n = Vue.observable({
  lang: localStorage.getItem('cp_lang') || 'zh'
})

export function setLang(l) {
  i18n.lang = l
  try { localStorage.setItem('cp_lang', l) } catch (e) {}
}

export function t(key) {
  const d = dict[i18n.lang] || dict.zh
  return d[key] != null ? d[key] : key
}

export default { i18n, setLang, t }
