export function createI18n() {
  const state = { lang: (localStorage.getItem('sk49_lang') || 'zh') }
  const t = (key) => {
    const parts = key.split('.')
    let cur = messages[state.lang]
    for (const p of parts) { if (cur == null) return key; cur = cur[p] }
    return cur == null ? key : cur
  }
  return {
    get lang() { return state.lang },
    set(l) { state.lang = l; localStorage.setItem('sk49_lang', l) },
    t
  }
}
