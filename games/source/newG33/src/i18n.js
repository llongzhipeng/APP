export function createI18n(initialLang = 'zh') {
  const state = { lang: initialLang }
  const t = (key, params) => {
    const fromDict = dict[state.lang] && dict[state.lang][key]
    const v = fromDict != null ? fromDict : key
    if (!params || typeof v !== 'string') return v
    return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : ''))
  }
  return { state, t, setLang(l) { state.lang = l } }
}
