export function t(lang, key, params) {
  let s = (DICT[lang] && DICT[lang][key]) || key
  if (params && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, (_, k) => params[k] != null ? params[k] : `{${k}}`)
  }
  return s
}

